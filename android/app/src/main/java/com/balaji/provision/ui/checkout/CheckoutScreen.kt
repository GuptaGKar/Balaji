/**
 * Checkout in three steps: address → payment → review.
 *
 * Every amount displayed comes from the server quote; the order is still priced
 * and authorised server-side. Only Cash on Delivery is offered because online
 * payments are disabled (M11 gate). Invoices are generated by the web billing
 * system only — this screen never creates or downloads one.
 */
@Composable
fun CheckoutScreen(
    cartViewModel: CartViewModel = hiltViewModel(),
    authViewModel: AuthViewModel = hiltViewModel(),
    accountViewModel: AccountViewModel = hiltViewModel(),
    homeViewModel: HomeViewModel = hiltViewModel(),
    onNavigateBack: () -> Unit = {},
    onNavigateToSignIn: () -> Unit = {},
    onOrderPlaced: () -> Unit = {}
) {
    var customerNote by remember { mutableStateOf("") }
    var selectedAddressId by remember { mutableStateOf<String?>(null) }
    var showAddressEditor by remember { mutableStateOf(false) }
    var addressDialogError by remember { mutableStateOf<String?>(null) }
    var step by rememberSaveable { mutableStateOf(1) }

    val cart by cartViewModel.cart.collectAsState()
    val quote by cartViewModel.quote.collectAsState()
    val placement by cartViewModel.orderPlacement.collectAsState()
    val authState by authViewModel.state.collectAsState()
    val accountState by accountViewModel.state.collectAsState()
    val homeState by homeViewModel.state.collectAsState()
    val session = authState.session
    val selectedAddress = accountState.addresses.firstOrNull { it.id == selectedAddressId }
        ?: accountState.addresses.firstOrNull { it.isDefault }
        ?: accountState.addresses.firstOrNull()
    val unavailableLines = quote?.lines?.filter { !it.available }.orEmpty()
    val isPlacingOrder = placement is OrderPlacementState.Placing

    // Optional order photo: picked at checkout, attached after the order is created.
    val photoContext = androidx.compose.ui.platform.LocalContext.current
    val photoViewModel: com.balaji.provision.ui.requests.ProductRequestsViewModel = hiltViewModel()
    var pendingPhotoUri by remember { mutableStateOf<Uri?>(null) }
    var attachingPhoto by remember { mutableStateOf(false) }
    val photoPicker = rememberLauncherForActivityResult(
        contract = ActivityResultContracts.GetContent()
    ) { uri -> if (uri != null) pendingPhotoUri = uri }

    val canContinueAddress = session != null && selectedAddress != null &&
        quote != null && unavailableLines.isEmpty() && cart.items.isNotEmpty()
    val canContinuePayment = quote != null && unavailableLines.isEmpty() && cart.items.isNotEmpty()
    val canPlaceOrder = canContinuePayment && !isPlacingOrder

    val snackbarHostState = remember { SnackbarHostState() }
    val coroutineScope = rememberCoroutineScope()
    val scrollState = rememberScrollState()

    LaunchedEffect(Unit) {
        if (session != null) accountViewModel.refresh()
    }

    LaunchedEffect(step) {
        scrollState.scrollTo(0)
    }

    BackHandler(enabled = step > 1) {
        step -= 1
    }

    LaunchedEffect(placement) {
        val failed = placement as? OrderPlacementState.Failed ?: return@LaunchedEffect
        cartViewModel.acknowledgeOrderPlacement()
        snackbarHostState.showSnackbar(failed.message)
    }

    // Attach the picked photo once the order exists. Failures are non-fatal: the order
    // is already placed, so the customer only loses the attachment.
    val placedForPhoto = placement as? OrderPlacementState.Placed
    LaunchedEffect(placedForPhoto?.orderId, pendingPhotoUri) {
        val orderId = placedForPhoto?.orderId?.takeIf { it.isNotBlank() } ?: return@LaunchedEffect
        val uri = pendingPhotoUri ?: return@LaunchedEffect
        attachingPhoto = true
        val mimeType = photoContext.contentResolver.getType(uri) ?: "image/jpeg"
        val bytes = withContext(Dispatchers.IO) {
            runCatching {
                photoContext.contentResolver.openInputStream(uri)?.use { it.readBytes() }
            }.getOrNull()
        }
        if (bytes == null || bytes.isEmpty()) {
            attachingPhoto = false
            pendingPhotoUri = null
            snackbarHostState.showSnackbar("Could not read that photo.")
            return@LaunchedEffect
        }
        photoViewModel.attachPhoto(orderId, bytes, mimeType) { success, message ->
            attachingPhoto = false
            if (success) pendingPhotoUri = null
            coroutineScope.launch { snackbarHostState.showSnackbar(message) }
        }
    }

    LaunchedEffect(accountState.addresses) {
        if (accountState.addresses.none { it.id == selectedAddressId }) {
            selectedAddressId = accountState.addresses.firstOrNull { it.isDefault }?.id
                ?: accountState.addresses.firstOrNull()?.id
        }
    }

    if (showAddressEditor) {
        AddressEditorDialog(
            initial = null,
            defaultName = accountState.profile?.displayName?.takeIf { it.isNotBlank() },
            defaultPhone = accountState.profile?.phone ?: session?.phone,
            isSaving = accountState.isSaving,
            serverError = addressDialogError,
            onDismiss = {
                if (!accountState.isSaving) {
                    showAddressEditor = false
                    addressDialogError = null
                }
            },
            onSave = { draft ->
                accountViewModel.saveAddress(draft, null) { success, saved, message ->
                    if (success && saved != null) {
                        selectedAddressId = saved.id
                        showAddressEditor = false
                        addressDialogError = null
                    } else {
                        addressDialogError = message
                    }
                }
            }
        )
    }

    val placedOrder = placement as? OrderPlacementState.Placed
    if (placedOrder != null && cart.items.isEmpty()) {
        Dialog(onDismissRequest = { }) {
            Card(
                modifier = Modifier.fillMaxWidth(),
                shape = RoundedCornerShape(24.dp),
                colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface)
            ) {
                Column(
                    modifier = Modifier.padding(24.dp),
                    horizontalAlignment = Alignment.CenterHorizontally,
                    verticalArrangement = Arrangement.spacedBy(16.dp)
                ) {
                    Box(
                        modifier = Modifier
                            .size(72.dp)
                            .clip(RoundedCornerShape(24.dp))
                            .background(MaterialTheme.appColors.successContainer),
                        contentAlignment = Alignment.Center
                    ) {
                        Icon(
                            Icons.Default.CheckCircle,
                            contentDescription = null,
                            tint = MaterialTheme.appColors.success,
                            modifier = Modifier.size(40.dp)
                        )
                    }

                    Column(horizontalAlignment = Alignment.CenterHorizontally) {
                        Text(
                            "Order placed successfully",
                            style = MaterialTheme.typography.titleLarge,
                            color = MaterialTheme.colorScheme.onSurface
                        )
                        Text(
                            "Order #${placedOrder.orderNumber}",
                            style = MaterialTheme.typography.titleMedium,
                            color = MaterialTheme.colorScheme.primary
                        )
                    }

                    Surface(
                        shape = RoundedCornerShape(14.dp),
                        color = MaterialTheme.colorScheme.surfaceVariant,
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        Column(
                            modifier = Modifier.padding(14.dp),
                            verticalArrangement = Arrangement.spacedBy(6.dp)
                        ) {
                            SummaryRow(label = "Payment", value = "Cash on Delivery (COD)")
                            SummaryRow(label = "Delivery", value = "Timing confirmed by the store")
                            SummaryRow(label = "Final bill", value = "Issued by the store at billing")
                        }
                    }

                    Button(
                        onClick = {
                            cartViewModel.acknowledgeOrderPlacement()
                            onOrderPlaced()
                        },
                        modifier = Modifier
                            .fillMaxWidth()
                            .height(50.dp),
                        shape = RoundedCornerShape(14.dp),
                        colors = ButtonDefaults.buttonColors(
                            containerColor = MaterialTheme.colorScheme.primary
                        )
                    ) {
                        Text(
                            "Track order in My Orders",
                            style = MaterialTheme.typography.titleSmall
                        )
                    }
                }
            }
        }
    }

    Box(modifier = Modifier.fillMaxSize()) {
        Column(modifier = Modifier.fillMaxSize()) {
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(start = 4.dp, end = 8.dp, top = 8.dp, bottom = 4.dp),
                verticalAlignment = Alignment.CenterVertically
            ) {
                IconButton(
                    onClick = {
                        if (step > 1) step -= 1 else onNavigateBack()
                    }
                ) {
                    Icon(Icons.Default.ArrowBack, contentDescription = "Back")
                }
                Column(modifier = Modifier.weight(1f)) {
                    Text(
                        text = "Checkout",
                        style = MaterialTheme.typography.titleLarge,
                        color = MaterialTheme.colorScheme.onSurface
                    )
                    Text(
                        text = "Step $step of 3",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }
                if (quote != null) {
                    Text(
                        text = formatPaise(quote?.grandTotalPaise ?: 0L),
                        style = MaterialTheme.typography.titleMedium,
                        fontWeight = FontWeight.Bold,
                        color = MaterialTheme.colorScheme.primary
                    )
                }
            }

            CheckoutStepIndicator(
                currentStep = step,
                modifier = Modifier.padding(horizontal = 16.dp, vertical = 8.dp)
            )

            Divider(color = MaterialTheme.colorScheme.outlineVariant)

            if (cart.items.isEmpty() && placedOrder == null) {
                Box(
                    modifier = Modifier.weight(1f),
                    contentAlignment = Alignment.Center
                ) {
                    EmptyState(
                        icon = Icons.Default.ShoppingCart,
                        title = "Your cart is empty",
                        message = "Add groceries to your cart before checking out.",
                        actionLabel = "Go back",
                        onAction = onNavigateBack
                    )
                }
            } else {
                Column(
                    modifier = Modifier
                        .weight(1f)
                        .verticalScroll(scrollState)
                        .padding(horizontal = 16.dp)
                        .padding(top = 12.dp, bottom = 12.dp),
                    verticalArrangement = Arrangement.spacedBy(14.dp)
                ) {
                    when (step) {
                        1 -> AddressStep(
                            sessionPresent = session != null,
                            isLoading = accountState.isLoading,
                            addresses = accountState.addresses,
                            selectedAddress = selectedAddress,
                            error = accountState.error,
                            isSaving = accountState.isSaving,
                            onSelectAddress = { selectedAddressId = it },
                            onAddAddress = {
                                addressDialogError = null
                                showAddressEditor = true
                            },
                            onSignIn = onNavigateToSignIn,
                            onRetry = { accountViewModel.refresh() },
                            unavailableLines = unavailableLines,
                            quotePresent = quote != null,
                            cartNotEmpty = cart.items.isNotEmpty(),
                            estimatedWindow = homeState.estimatedWindow,
                            deliveryFeePaise = quote?.deliveryFeePaise,
                            amountToFreeDelivery = quote?.amountToFreeDelivery ?: 0L,
                            onRetryQuote = { cartViewModel.refreshQuote() }
                        )

                        2 -> PaymentStep(
                            customerNote = customerNote,
                            onCustomerNoteChange = { customerNote = it },
                            quoteFeeNote = quote?.feeRuleNote
                        )

                        else -> Column(verticalArrangement = Arrangement.spacedBy(12.dp)) {
                            ReviewStep(
                                address = selectedAddress,
                                customerNote = customerNote,
                                quote = quote,
                                unavailableLines = unavailableLines,
                                onEditAddress = { step = 1 },
                                onEditPayment = { step = 2 },
                                onRetryQuote = { cartViewModel.refreshQuote() }
                            )
                            OrderPhotoRow(
                                hasPhoto = pendingPhotoUri != null,
                                busy = attachingPhoto,
                                onPick = { photoPicker.launch("image/*") },
                                onClear = { pendingPhotoUri = null }
                            )
                        }
                    }
                }

                StickyBottomBar {
                    Button(
                        onClick = {
                            when (step) {
                                1 -> {
                                    if (selectedAddress == null) {
                                        coroutineScope.launch {
                                            snackbarHostState.showSnackbar(
                                                "Add or select a delivery address."
                                            )
                                        }
                                    } else {
                                        step = 2
                                    }
                                }

                                2 -> step = 3

                                else -> {
                                    val address = selectedAddress
                                    if (address == null) {
                                        step = 1
                                        coroutineScope.launch {
                                            snackbarHostState.showSnackbar(
                                                "Add or select a delivery address."
                                            )
                                        }
                                        return@Button
                                    }
                                    cartViewModel.placeOrder(
                                        AddressRequest(
                                            recipient_name = address.recipientName,
                                            phone = address.phone,
                                            address_lines = address.addressLines,
                                            landmark = address.landmark,
                                            area = address.area,
                                            city = address.city,
                                            state = address.state,
                                            postal_code = address.postalCode,
                                            lat = address.lat,
                                            lng = address.lng
                                        ),
                                        customerNote.ifBlank { null }
                                    )
                                }
                            }
                        },
                        enabled = when (step) {
                            1 -> canContinueAddress
                            2 -> canContinuePayment
                            else -> canPlaceOrder
                        },
                        modifier = Modifier
                            .fillMaxWidth()
                            .height(50.dp),
                        shape = RoundedCornerShape(14.dp),
                        colors = ButtonDefaults.buttonColors(
                            containerColor = MaterialTheme.colorScheme.primary
                        )
                    ) {
                        if (isPlacingOrder && step == 3) {
                            CircularProgressIndicator(
                                color = MaterialTheme.colorScheme.onPrimary,
                                modifier = Modifier.size(22.dp),
                                strokeWidth = 2.dp
                            )
                        } else {
                            Text(
                                text = when (step) {
                                    1 -> "Continue to payment"
                                    2 -> "Review order"
                                    else -> "Place order"
                                },
                                style = MaterialTheme.typography.titleSmall
                            )
                        }
                    }
                }
            }
        }

        SnackbarHost(
            hostState = snackbarHostState,
            modifier = Modifier
                .align(Alignment.BottomCenter)
                .padding(bottom = 96.dp, start = 16.dp, end = 16.dp)
        )
    }
}

@Composable
private fun AddressStep(
    sessionPresent: Boolean,
    isLoading: Boolean,
    addresses: List<SavedAddress>,
    selectedAddress: SavedAddress?,
    error: String?,
    isSaving: Boolean,
    onSelectAddress: (String) -> Unit,
    onAddAddress: () -> Unit,
    onSignIn: () -> Unit,
    onRetry: () -> Unit,
    unavailableLines: List<com.balaji.provision.domain.model.QuoteBreakdown.Line>,
    quotePresent: Boolean,
    cartNotEmpty: Boolean,
    estimatedWindow: String?,
    deliveryFeePaise: Long?,
    amountToFreeDelivery: Long,
    onRetryQuote: () -> Unit
) {
    Card(
        modifier = Modifier.fillMaxWidth(),
        shape = RoundedCornerShape(18.dp),
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
        elevation = CardDefaults.cardElevation(defaultElevation = 1.dp)
    ) {
        Column(
            modifier = Modifier.padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(10.dp)
        ) {
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Text(
                    text = "Delivery address",
                    style = MaterialTheme.typography.titleMedium,
                    color = MaterialTheme.colorScheme.onSurface
                )
                if (sessionPresent) {
                    TextButton(onClick = onAddAddress, enabled = !isSaving) {
                        Icon(
                            Icons.Default.Add,
                            contentDescription = null,
                            modifier = Modifier.size(18.dp)
                        )
                        Text(" Add new")
                    }
                }
            }
            Divider(color = MaterialTheme.colorScheme.outlineVariant)

            when {
                !sessionPresent -> {
                    Text(
                        "Sign in to place your order. Guest checkout is not available.",
                        style = MaterialTheme.typography.bodyMedium,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                    Button(onClick = onSignIn) { Text("Sign in") }
                }

                isLoading && addresses.isEmpty() -> Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.Center,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    CircularProgressIndicator(
                        modifier = Modifier.size(24.dp),
                        strokeWidth = 3.dp
                    )
                }

                addresses.isEmpty() -> {
                    Text(
                        "Add a delivery address once and reuse it for every order.",
                        style = MaterialTheme.typography.bodyMedium,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                    Button(onClick = onAddAddress, enabled = !isSaving) {
                        Text("Add delivery address")
                    }
                }

                else -> addresses.forEach { address ->
                    CheckoutAddressOption(
                        address = address,
                        selected = address.id == selectedAddress?.id,
                        onSelect = { onSelectAddress(address.id) }
                    )
                }
            }

            if (error != null) {
                Text(
                    error,
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.error
                )
                TextButton(onClick = onRetry) { Text("Retry") }
            }
        }
    }

    Card(
        modifier = Modifier.fillMaxWidth(),
        shape = RoundedCornerShape(18.dp),
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
        elevation = CardDefaults.cardElevation(defaultElevation = 1.dp)
    ) {
        Column(
            modifier = Modifier.padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(8.dp)
        ) {
            Text(
                "Delivery option",
                style = MaterialTheme.typography.titleMedium,
                color = MaterialTheme.colorScheme.onSurface
            )
            Row(
                modifier = Modifier.fillMaxWidth(),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                Icon(
                    Icons.Default.LocalShipping,
                    contentDescription = null,
                    tint = MaterialTheme.appColors.success
                )
                Column(modifier = Modifier.weight(1f)) {
                    Text(
                        "Standard delivery",
                        style = MaterialTheme.typography.titleSmall,
                        color = MaterialTheme.colorScheme.onSurface
                    )
                    Text(
                        text = estimatedWindow?.let { "Within $it" }
                            ?: "Timing confirmed by the store",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }
                Text(
                    text = when {
                        deliveryFeePaise == null -> "—"
                        deliveryFeePaise == 0L -> "FREE"
                        else -> formatPaise(deliveryFeePaise)
                    },
                    style = MaterialTheme.typography.titleSmall,
                    fontWeight = FontWeight.SemiBold,
                    color = if (deliveryFeePaise == 0L) {
                        MaterialTheme.appColors.success
                    } else {
                        MaterialTheme.colorScheme.onSurface
                    }
                )
            }
        }
    }

    if (amountToFreeDelivery > 0L) {
        Surface(
            shape = RoundedCornerShape(14.dp),
            color = MaterialTheme.appColors.warningContainer,
            modifier = Modifier.fillMaxWidth()
        ) {
            Text(
                text = "Add ${formatPaise(amountToFreeDelivery)} more for FREE delivery.",
                style = MaterialTheme.typography.bodySmall,
                fontWeight = FontWeight.SemiBold,
                color = MaterialTheme.appColors.onWarningContainer,
                modifier = Modifier.padding(14.dp)
            )
        }
    }

    if (!quotePresent && cartNotEmpty) {
        Card(
            modifier = Modifier.fillMaxWidth(),
            colors = CardDefaults.cardColors(
                containerColor = MaterialTheme.colorScheme.errorContainer
            ),
            shape = RoundedCornerShape(18.dp)
        ) {
            Column(Modifier.padding(14.dp)) {
                Text(
                    "Delivery charge and total could not be loaded. Check your connection and try again.",
                    color = MaterialTheme.colorScheme.onErrorContainer,
                    style = MaterialTheme.typography.bodyMedium
                )
                Button(
                    onClick = onRetryQuote,
                    modifier = Modifier.padding(top = 8.dp)
                ) {
                    Text("Retry total")
                }
            }
        }
    }

    if (unavailableLines.isNotEmpty()) {
        UnavailableCard(unavailableLines)
    }
}

@Composable
private fun PaymentStep(
    customerNote: String,
    onCustomerNoteChange: (String) -> Unit,
    quoteFeeNote: String?
) {
    Card(
        modifier = Modifier.fillMaxWidth(),
        shape = RoundedCornerShape(18.dp),
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
        elevation = CardDefaults.cardElevation(defaultElevation = 1.dp)
    ) {
        Column(
            modifier = Modifier.padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(10.dp)
        ) {
            Text(
                text = "Payment method",
                style = MaterialTheme.typography.titleMedium,
                color = MaterialTheme.colorScheme.onSurface
            )
            Divider(color = MaterialTheme.colorScheme.outlineVariant)

            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .selectable(
                        selected = true,
                        role = Role.RadioButton,
                        onClick = {}
                    )
                    .padding(vertical = 4.dp),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.spacedBy(8.dp)
            ) {
                RadioButton(selected = true, onClick = {})
                Icon(
                    Icons.Default.Wallet,
                    contentDescription = null,
                    tint = MaterialTheme.colorScheme.primary
                )
                Column {
                    Text(
                        "Cash on Delivery (COD)",
                        style = MaterialTheme.typography.titleSmall,
                        color = MaterialTheme.colorScheme.onSurface
                    )
                    Text(
                        "Pay in cash when groceries arrive at your doorstep.",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }
            }

            Surface(
                shape = RoundedCornerShape(14.dp),
                color = MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.5f),
                modifier = Modifier.fillMaxWidth()
            ) {
                Row(
                    modifier = Modifier.padding(14.dp),
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.spacedBy(10.dp)
                ) {
                    Icon(
                        Icons.Default.Lock,
                        contentDescription = null,
                        tint = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                    Column(modifier = Modifier.weight(1f)) {
