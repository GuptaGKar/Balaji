/** Existing catalogue attributes, shown only when present. */
@Composable
private fun AttributeBlock(product: Product) {
    val rows = buildList {
        add("SKU" to product.sku)
        add(
            "Unit" to when (product.quantityType) {
                QuantityType.WEIGHTED -> "Sold by weight"
                QuantityType.PACKED -> product.unitLabel
            }
        )
        if (product.quantityType == QuantityType.WEIGHTED) {
            add("Minimum" to formatWeightGrams(product.minQty))
            if (product.maxQty != null) {
                add("Maximum" to formatWeightGrams(product.maxQty))
            }
        }
    }
    Card(
        modifier = Modifier.fillMaxWidth(),
        colors = CardDefaults.cardColors(
            containerColor = MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.45f)
        ),
        shape = RoundedCornerShape(12.dp)
    ) {
        Column(
            modifier = Modifier.padding(12.dp),
            verticalArrangement = Arrangement.spacedBy(6.dp)
        ) {
            rows.forEach { (label, value) ->
                Row(modifier = Modifier.fillMaxWidth()) {
                    Text(
                        text = label,
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        modifier = Modifier.weight(1f)
                    )
                    Text(
                        text = value,
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurface,
                        fontWeight = FontWeight.Medium
                    )
                }
            }
        }
    }
}

/**
 * Sticky purchase bar: orange ADD for packed goods, weight chooser for weighted
 * goods, and a stepper once the pack is in the basket. Out-of-stock packs
 * disable the whole bar.
 */
@Composable
private fun PurchaseBar(
    product: Product,
    inCartQty: Long?,
    pendingQty: Long,
    onAdd: (Long) -> Unit,
    onUpdate: (Long) -> Unit,
    onChooseWeight: () -> Unit
) {
    val inCart = inCartQty != null
    val haptics = LocalHapticFeedback.current
    val quantity = inCartQty ?: pendingQty

    StickyBottomBar {
        if (inCart) {
            Column(modifier = Modifier.weight(1f)) {
                Text(
                    text = "In cart · ${formatPaise(lineTotalPaise(product.pricePaise, product.priceBasisQty, quantity))}",
                    style = MaterialTheme.typography.labelMedium,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
                Text(
                    text = if (product.quantityType == QuantityType.WEIGHTED) {
                        formatWeightGrams(quantity)
                    } else {
                        "$quantity ${product.unitLabel}"
                    },
                    style = MaterialTheme.typography.titleSmall,
                    color = MaterialTheme.colorScheme.primary
                )
            }
            OutlinedQuantityStepper(
                value = inCartQty ?: product.minQty,
                onDecrease = {
                    onUpdate((inCartQty ?: product.minQty) - product.stepQty)
                },
                onIncrease = {
                    onUpdate(
                        ((inCartQty ?: product.minQty) + product.stepQty)
                            .coerceAtMost(product.maxOrderQty)
                    )
                },
                decreaseContentDescription = "Decrease quantity of ${product.name}",
                increaseContentDescription = "Increase quantity of ${product.name}",
                canIncrease = (inCartQty ?: 0L) < product.maxOrderQty
            )
        } else {
            when {
                !product.isInStock -> Button(
                    onClick = {},
                    enabled = false,
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(50.dp),
                    shape = RoundedCornerShape(14.dp)
                ) {
                    Text("Out of stock", style = MaterialTheme.typography.labelLarge)
                }

                product.quantityType == QuantityType.WEIGHTED -> Button(
                    onClick = onChooseWeight,
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(50.dp),
                    shape = RoundedCornerShape(14.dp),
                    colors = ButtonDefaults.buttonColors(
                        containerColor = MaterialTheme.colorScheme.primary
                    )
                ) {
                    Icon(
                        Icons.Default.Scale,
                        contentDescription = null,
                        modifier = Modifier.size(18.dp)
                    )
                    Spacer(modifier = Modifier.width(6.dp))
                    Text("Choose weight", style = MaterialTheme.typography.labelLarge)
                }

                else -> Button(
                    onClick = {
                        haptics.performHapticFeedback(HapticFeedbackType.TextHandleMove)
                        onAdd(pendingQty)
                    },
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(50.dp)
                        .clearAndSetSemantics {
                            contentDescription = "Add ${product.name}, ${product.packLabel}, to cart"
                        },
                    shape = RoundedCornerShape(14.dp),
                    colors = ButtonDefaults.buttonColors(
                        containerColor = MaterialTheme.colorScheme.primary
                    )
                ) {
                    Icon(
                        Icons.Default.Add,
                        contentDescription = null,
                        modifier = Modifier.size(18.dp)
                    )
                    Spacer(modifier = Modifier.width(4.dp))
                    Text(
                        "Add to Cart",
                        style = MaterialTheme.typography.labelLarge,
                        fontWeight = FontWeight.Bold
                    )
                }
            }
        }
    }
}

private fun perUnitLabel(product: Product): String = when (product.quantityType) {
    QuantityType.WEIGHTED -> when (product.priceBasisQty) {
        1000L -> "/ kg"
        100L -> "/ 100 g"
        else -> "/ g"
    }
    QuantityType.PACKED -> "/ ${product.unitLabel}"
}
