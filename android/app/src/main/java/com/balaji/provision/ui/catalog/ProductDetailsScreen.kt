/**
 * Product details with a pack-size selector.
 *
 * The screen is driven entirely by the real catalogue: [group] carries every
 * pack variant of one base product, each with its own price, stock and
 * availability. Selecting a pack swaps [selectedVariant], which re-renders the
 * price, pack label, stock pill and purchase controls. Each variant is its own
 * product row, so the cart already tracks packs independently.
 *
 * No wishlist, brand or rating data exists in this schema, so those rows are
 * omitted rather than faked. Invoices/bills are generated by the web admin app
 * only; this screen never creates or downloads one.
 */
@Composable
fun ProductDetailsScreen(
    group: ProductVariantGroup,
    cart: Cart,
    onBack: () -> Unit,
    onAddToCart: (productId: String, qtyBase: Long) -> Unit,
    onUpdateQuantity: (productId: String, qtyBase: Long) -> Unit,
    onRemoveFromCart: (productId: String) -> Unit,
    onOpenCart: () -> Unit = {},
    onShare: (() -> Unit)? = null
) {
    var selectedVariantId by remember(group.groupId) {
        mutableStateOf(group.defaultVariant.id)
    }
    val selected = group.variants.firstOrNull { it.id == selectedVariantId }
        ?: group.defaultVariant

    val cartItemForSelected = cart.items.find { it.productId == selected.id }
    val isWeighted = selected.quantityType == QuantityType.WEIGHTED
    var showWeightDialog by remember { mutableStateOf(false) }
    var pendingQty by remember(selected.id) { mutableStateOf(selected.minQty) }

    if (showWeightDialog && isWeighted) {
        WeightedQuantityDialog(
            product = selected,
            currentQtyBaseGrams = cartItemForSelected?.qtyBase ?: selected.minQty,
            onDismiss = { showWeightDialog = false },
            onConfirmQtyGrams = { grams ->
                if (cartItemForSelected == null) {
                    onAddToCart(selected.id, grams)
                } else {
                    onUpdateQuantity(selected.id, grams)
                }
                showWeightDialog = false
            }
        )
    }

    Column(modifier = Modifier.fillMaxSize()) {
        // Header: back, share/cart actions.
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .padding(start = 4.dp, end = 6.dp, top = 8.dp, bottom = 4.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            IconButton(onClick = onBack) {
                Icon(Icons.Default.ArrowBack, contentDescription = "Back")
            }
            Text(
                text = "Product details",
                style = MaterialTheme.typography.titleMedium,
                color = MaterialTheme.colorScheme.onSurface,
                modifier = Modifier.weight(1f)
            )
            if (onShare != null) {
                IconButton(onClick = onShare) {
                    Icon(Icons.Default.Share, contentDescription = "Share product")
                }
            }
            CartAction(count = cart.items.size, onClick = onOpenCart)
        }

        Column(
            modifier = Modifier
                .weight(1f)
                .verticalScroll(rememberScrollState())
        ) {
            ProductImage(product = selected)

            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 16.dp),
                verticalArrangement = Arrangement.spacedBy(14.dp)
            ) {
                Spacer(modifier = Modifier.height(6.dp))

                Column(verticalArrangement = Arrangement.spacedBy(4.dp)) {
                    Text(
                        text = selected.name,
                        style = MaterialTheme.typography.headlineSmall,
                        fontWeight = FontWeight.SemiBold,
                        color = MaterialTheme.colorScheme.onSurface
                    )
                    Text(
                        text = selected.packLabel,
                        style = MaterialTheme.typography.bodyMedium,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }

                PriceBlock(product = selected)

                Row(
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    StockBlock(product = selected)
                    StatusPill(
                        text = "Cash on Delivery",
                        containerColor = MaterialTheme.colorScheme.surfaceVariant,
                        contentColor = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }

                if (group.hasMultipleVariants) {
                    PackSelector(
                        group = group,
                        selectedVariantId = selected.id,
                        onSelected = { variantId ->
                            selectedVariantId = variantId
                        }
                    )
                }

                if (!isWeighted && cartItemForSelected == null) {
                    QuantityBlock(
                        value = pendingQty,
                        canDecrease = pendingQty > selected.minQty,
                        canIncrease = pendingQty < selected.maxOrderQty,
                        onDecrease = {
                            pendingQty = (pendingQty - selected.stepQty)
                                .coerceAtLeast(selected.minQty)
                        },
                        onIncrease = {
                            pendingQty = (pendingQty + selected.stepQty)
                                .coerceAtMost(selected.maxOrderQty)
                        }
                    )
                }

                selected.description?.takeIf { it.isNotBlank() }?.let { description ->
                    DescriptionBlock(description = description)
                }

                AttributeBlock(product = selected)

                Surface(
                    shape = RoundedCornerShape(14.dp),
                    color = MaterialTheme.colorScheme.primaryContainer,
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Column(
                        modifier = Modifier.padding(14.dp),
                        verticalArrangement = Arrangement.spacedBy(6.dp)
                    ) {
                        Text(
                            "Good to know",
                            style = MaterialTheme.typography.titleSmall,
                            fontWeight = FontWeight.SemiBold,
                            color = MaterialTheme.colorScheme.onSurface
                        )
                        Text(
                            "Pay cash on delivery. The store confirms every order before packing.",
                            style = MaterialTheme.typography.bodySmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    }
                }

                Spacer(modifier = Modifier.height(20.dp))
            }
        }

        PurchaseBar(
            product = selected,
            inCartQty = cartItemForSelected?.qtyBase,
            pendingQty = pendingQty,
            onAdd = { qty -> onAddToCart(selected.id, qty) },
            onUpdate = { newQty ->
                if (newQty <= 0) onRemoveFromCart(selected.id)
                else onUpdateQuantity(selected.id, newQty)
            },
            onChooseWeight = { showWeightDialog = true }
        )
    }
}

@Composable
private fun CartAction(count: Int, onClick: () -> Unit) {
    Box {
        IconButton(onClick = onClick) {
            Icon(
                Icons.Default.ShoppingCart,
                contentDescription = if (count > 0) "Open cart, $count items" else "Open cart"
            )
        }
        if (count > 0) {
            Surface(
                shape = CircleShape,
                color = MaterialTheme.colorScheme.primary,
                modifier = Modifier
                    .align(Alignment.TopEnd)
                    .padding(top = 4.dp, end = 4.dp)
            ) {
                Text(
                    text = if (count > 9) "9+" else count.toString(),
                    style = MaterialTheme.typography.labelSmall,
                    fontWeight = FontWeight.Bold,
                    color = MaterialTheme.colorScheme.onPrimary,
                    modifier = Modifier.padding(horizontal = 5.dp, vertical = 1.dp)
                )
            }
        }
    }
}

/**
 * Shown while the pack group is being resolved from the live catalogue (for
 * example after a cold start deep-linked straight into a product).
 */
@Composable
fun ProductDetailsLoading(onBack: () -> Unit) {
    Column(modifier = Modifier.fillMaxSize()) {
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .padding(start = 4.dp, end = 6.dp, top = 8.dp, bottom = 4.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            IconButton(onClick = onBack) {
                Icon(Icons.Default.ArrowBack, contentDescription = "Back")
            }
            Text("Product", style = MaterialTheme.typography.titleMedium)
        }
        Box(
            modifier = Modifier
                .fillMaxSize()
                .padding(24.dp),
            contentAlignment = Alignment.Center
        ) {
            CircularProgressIndicator()
        }
    }
}

@Composable
private fun ProductImage(product: Product) {
    Box(
        modifier = Modifier
            .fillMaxWidth()
            .background(MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.45f))
            .aspectRatio(1.25f),
        contentAlignment = Alignment.Center
    ) {
        ProductThumb(
            name = product.name,
            size = 200,
            imageUrl = product.imagePath,
            modifier = Modifier
                .size(200.dp)
                .clearAndSetSemantics {
                    contentDescription = "Image of ${product.name}"
                }
        )
    }
}

@Composable
private fun PriceBlock(product: Product) {
    Row(
        verticalAlignment = Alignment.Bottom,
        horizontalArrangement = Arrangement.spacedBy(8.dp)
    ) {
        MoneyText(
            text = formatPaise(product.pricePaise),
            style = MaterialTheme.typography.headlineSmall,
            color = MaterialTheme.colorScheme.primary
        )
        if (product.hasDiscount) {
            Text(
                text = formatPaise(product.mrpPaise!!),
                style = MaterialTheme.typography.titleMedium.copy(textDecoration = TextDecoration.LineThrough),
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                modifier = Modifier.padding(bottom = 2.dp)
            )
            Surface(
                shape = RoundedCornerShape(4.dp),
                color = MaterialTheme.colorScheme.primaryContainer,
                modifier = Modifier.padding(bottom = 3.dp)
            ) {
                Text(
                    text = "${product.discountPercent}% OFF",
                    style = MaterialTheme.typography.labelSmall,
                    fontWeight = FontWeight.Bold,
                    color = MaterialTheme.colorScheme.primary,
                    modifier = Modifier.padding(horizontal = 6.dp, vertical = 2.dp)
                )
            }
        }
        Text(
            text = perUnitLabel(product),
            style = MaterialTheme.typography.bodyMedium,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
            modifier = Modifier.padding(bottom = 3.dp)
        )
    }
}

@Composable
private fun StockBlock(product: Product) {
    when {
        !product.isInStock -> StatusPill(
            text = "Out of stock",
            icon = Icons.Default.Warning,
            containerColor = MaterialTheme.colorScheme.errorContainer,
            contentColor = MaterialTheme.colorScheme.onErrorContainer
        )
        product.isLowStock -> StatusPill(
            text = "Only a few left",
            icon = Icons.Default.Warning,
            containerColor = MaterialTheme.appColors.warningContainer,
            contentColor = MaterialTheme.appColors.onWarningContainer
        )
        else -> StatusPill(
            text = "In stock",
            icon = Icons.Default.CheckCircle,
            containerColor = MaterialTheme.appColors.successContainer,
            contentColor = MaterialTheme.appColors.onSuccessContainer
        )
    }
}

/**
 * Pack-size selector. Selected pack is orange. Unavailable packs stay
 * selectable so customers can inspect them, but purchase controls disable.
 */
@Composable
private fun PackSelector(
    group: ProductVariantGroup,
    selectedVariantId: String,
    onSelected: (String) -> Unit
) {
    Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
        Text(
            text = "Pack size",
            style = MaterialTheme.typography.titleSmall,
            fontWeight = FontWeight.SemiBold,
            color = MaterialTheme.colorScheme.onSurface
        )
        Row(
            horizontalArrangement = Arrangement.spacedBy(8.dp),
            modifier = Modifier
                .fillMaxWidth()
                .horizontalScroll(rememberScrollState())
        ) {
            group.variants.forEach { variant ->
                val selected = variant.id == selectedVariantId
                Surface(
                    onClick = { onSelected(variant.id) },
                    shape = RoundedCornerShape(12.dp),
                    color = if (selected) {
                        MaterialTheme.colorScheme.primaryContainer
                    } else {
                        MaterialTheme.colorScheme.surface
                    },
                    border = BorderStroke(
                        width = if (selected) 1.5.dp else 1.dp,
                        color = if (selected) {
                            MaterialTheme.colorScheme.primary
                        } else {
                            MaterialTheme.colorScheme.outlineVariant
                        }
                    )
                ) {
                    Column(
                        modifier = Modifier.padding(horizontal = 12.dp, vertical = 8.dp),
                        verticalArrangement = Arrangement.spacedBy(2.dp)
                    ) {
                        Text(
                            text = variant.packLabel,
                            style = MaterialTheme.typography.labelLarge,
                            fontWeight = if (selected) FontWeight.Bold else FontWeight.Medium,
                            color = if (selected) {
                                MaterialTheme.colorScheme.primary
                            } else {
                                MaterialTheme.colorScheme.onSurface
                            }
                        )
                        if (variant.hasDiscount) {
                            Row(
                                horizontalArrangement = Arrangement.spacedBy(4.dp),
                                verticalAlignment = Alignment.CenterVertically
                            ) {
                                Text(
                                    text = "${formatPaise(variant.pricePaise)}${perUnitLabel(variant)}",
                                    style = MaterialTheme.typography.labelSmall,
                                    fontWeight = FontWeight.Bold,
                                    color = MaterialTheme.colorScheme.onSurface
                                )
                                Text(
                                    text = formatPaise(variant.mrpPaise!!),
                                    style = MaterialTheme.typography.labelSmall.copy(textDecoration = TextDecoration.LineThrough),
                                    color = MaterialTheme.colorScheme.onSurfaceVariant
                                )
                            }
                        } else {
                            Text(
                                text = "${formatPaise(variant.pricePaise)}${perUnitLabel(variant)}",
                                style = MaterialTheme.typography.labelSmall,
                                color = MaterialTheme.colorScheme.onSurfaceVariant
                            )
                        }
                        if (!variant.isInStock) {
                            Text(
                                text = "Out of stock",
                                style = MaterialTheme.typography.labelSmall,
                                color = MaterialTheme.colorScheme.error
                            )
                        }
                    }
                }
            }
        }
        Text(
            text = "${group.variants.size} pack sizes available",
            style = MaterialTheme.typography.bodySmall,
            color = MaterialTheme.colorScheme.onSurfaceVariant
        )
    }
}

@Composable
private fun QuantityBlock(
    value: Long,
    canDecrease: Boolean,
    canIncrease: Boolean,
    onDecrease: () -> Unit,
    onIncrease: () -> Unit
) {
    Row(
        modifier = Modifier.fillMaxWidth(),
        verticalAlignment = Alignment.CenterVertically,
        horizontalArrangement = Arrangement.SpaceBetween
    ) {
        Text(
            text = "Quantity",
            style = MaterialTheme.typography.titleSmall,
            fontWeight = FontWeight.SemiBold,
            color = MaterialTheme.colorScheme.onSurface
        )
        OutlinedQuantityStepper(
            value = value,
            onDecrease = onDecrease,
            onIncrease = onIncrease,
            decreaseContentDescription = "Decrease quantity",
            increaseContentDescription = "Increase quantity",
            canDecrease = canDecrease,
            canIncrease = canIncrease
        )
    }
}

